//! Markdown documentation generator (`sheaf docs`) derived from Clap command metadata.

use clap::CommandFactory;
use std::fmt::Write as _;

use crate::cli::Cli;

fn visible(arg: &clap::Arg) -> bool {
    !(arg.get_id() == "help" || arg.get_id() == "version" || arg.is_hide_set())
}

fn arg_label(arg: &clap::Arg) -> String {
    if let Some(long) = arg.get_long() {
        if let Some(short) = arg.get_short() {
            format!("`-{short}, --{long}`")
        } else {
            format!("`--{long}`")
        }
    } else {
        format!("`<{}>`", arg.get_id())
    }
}

fn arg_value(arg: &clap::Arg) -> String {
    let takes_value = !matches!(
        arg.get_action(),
        clap::ArgAction::SetTrue | clap::ArgAction::SetFalse | clap::ArgAction::Count
    );
    if !takes_value {
        return "-".to_string();
    }
    arg.get_value_names()
        .and_then(|v| v.first().map(|s| format!("`<{s}>`")))
        .unwrap_or_else(|| "-".to_string())
}

fn arg_help(arg: &clap::Arg) -> String {
    let mut help = arg
        .get_help()
        .map(|h| h.to_string().replace('\n', " "))
        .unwrap_or_default();
    let defaults: Vec<String> = arg
        .get_default_values()
        .iter()
        .map(|v| v.to_string_lossy().into_owned())
        .collect();
    if !defaults.is_empty() && !arg.is_positional() {
        let takes_value = !matches!(
            arg.get_action(),
            clap::ArgAction::SetTrue | clap::ArgAction::SetFalse | clap::ArgAction::Count
        );
        if takes_value {
            help.push_str(&format!(" (default: `{}`)", defaults.join(",")));
        }
    }
    let possible: Vec<String> = arg
        .get_possible_values()
        .iter()
        .filter(|v| !v.is_hide_set())
        .map(|v| format!("`{}`", v.get_name()))
        .collect();
    if !possible.is_empty() {
        help.push_str(&format!(" (values: {})", possible.join(", ")));
    }
    help.replace('|', "\\|")
}

fn anchor(path: &str) -> String {
    format!("sheaf-{}", path.replace(' ', "-"))
}

/// Recursively collects visible leaf commands with their full path.
fn collect_leaves<'a>(
    cmd: &'a clap::Command,
    prefix: &str,
    out: &mut Vec<(String, &'a clap::Command)>,
) {
    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        let path = if prefix.is_empty() {
            sub.get_name().to_string()
        } else {
            format!("{prefix} {}", sub.get_name())
        };
        if sub.has_subcommands() {
            collect_leaves(sub, &path, out);
        } else {
            out.push((path, sub));
        }
    }
}

/// Generates the complete Markdown documentation for all Sheaf CLI commands and options.
///
/// Every visible leaf command (including nested ones such as `pages rotate`) gets its own
/// section. Global options are derived from the clap definition as well.
pub fn generate_cli_markdown() -> String {
    let mut out = String::new();
    let root = Cli::command();
    let mut leaves = Vec::new();
    collect_leaves(&root, "", &mut leaves);

    let _ = writeln!(out, "# Sheaf CLI Reference\n");
    let _ = writeln!(
        out,
        "> **Note:** This documentation is automatically generated from the Clap command definition.\n> Do not edit this file by hand. Update it with `UPDATE_DOCS=1 cargo test --test docs_sync_test`.\n"
    );

    let _ = writeln!(out, "## Table of Contents\n");
    for (path, _) in &leaves {
        let _ = writeln!(out, "- [`sheaf {path}`](#{})", anchor(path));
    }
    let _ = writeln!(out);

    let _ = writeln!(out, "## Global Options\n");
    let _ = writeln!(
        out,
        "These options are supported across all `sheaf` subcommands:\n"
    );
    let _ = writeln!(out, "| Option | Value | Description |");
    let _ = writeln!(out, "| :--- | :--- | :--- |");
    for arg in root
        .get_arguments()
        .filter(|a| visible(a) && a.is_global_set())
    {
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            arg_label(arg),
            arg_value(arg),
            arg_help(arg)
        );
    }
    let _ = writeln!(out);

    for (path, sub) in &leaves {
        let _ = writeln!(out, "## `sheaf {path}`\n");
        if let Some(about) = sub.get_long_about().or_else(|| sub.get_about()) {
            let _ = writeln!(out, "{}\n", about);
        }

        let _ = writeln!(out, "### Options & Arguments\n");
        let _ = writeln!(
            out,
            "| Option / Argument | Value | Required | Description |"
        );
        let _ = writeln!(out, "| :--- | :--- | :--- | :--- |");

        for arg in sub
            .get_arguments()
            .filter(|a| visible(a) && !a.is_global_set())
        {
            let required_str = if arg.is_required_set() { "Yes" } else { "No" };
            let _ = writeln!(
                out,
                "| {} | {} | {required_str} | {} |",
                arg_label(arg),
                arg_value(arg),
                arg_help(arg)
            );
        }
        let _ = writeln!(out);

        if let Some(after_help) = sub.get_after_help() {
            let mut examples = Vec::new();
            let mut notes = Vec::new();
            for line in after_help.to_string().lines() {
                let trimmed = line.trim();
                if trimmed.is_empty()
                    || trimmed.starts_with("Examples:")
                    || trimmed.starts_with("Notes:")
                {
                    continue;
                }
                if trimmed.starts_with("sheaf ")
                    || trimmed.starts_with("printf ")
                    || trimmed.starts_with("export ")
                    || trimmed.starts_with("SOURCE_DATE_EPOCH")
                {
                    examples.push(trimmed.to_string());
                } else {
                    notes.push(trimmed.to_string());
                }
            }
            if !notes.is_empty() {
                let _ = writeln!(out, "### Notes\n");
                for n in notes {
                    let _ = writeln!(out, "- {n}");
                }
                let _ = writeln!(out);
            }
            if !examples.is_empty() {
                let _ = writeln!(out, "### Examples\n");
                let _ = writeln!(out, "```bash");
                for e in examples {
                    let _ = writeln!(out, "{e}");
                }
                let _ = writeln!(out, "```\n");
            }
        }
    }

    out
}

use crate::cli::DocsArgs;
use crate::commands::{Command, Ctx, Outcome};
use serde::Serialize;
use sheaf_core::SheafError;

/// Empty report for docs command.
#[derive(Debug, Clone, Serialize)]
pub struct DocsReport {
    /// Markdown documentation text.
    pub markdown: String,
}

impl Command for DocsArgs {
    type Report = DocsReport;

    fn name(&self) -> &'static str {
        "docs"
    }

    fn run(&self, _ctx: &Ctx) -> Result<Outcome<Self::Report>, SheafError> {
        let markdown = generate_cli_markdown();
        Ok(Outcome {
            report: DocsReport { markdown },
            warnings: Vec::new(),
            dry_run: false,
            failure: None,
        })
    }

    fn format_human(&self, report: &Self::Report, _dry_run: bool) -> String {
        report.markdown.clone()
    }
}
